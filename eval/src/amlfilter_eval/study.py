"""The name-similarity study, scored.

This is the committed replacement for a number that lived only in a code comment.
`engine/scoring.ts` and `engine/fuzzyText.ts` each cite a measurement — token_set
at 0.60 scoring 82.8% recall at 0.37% FPR, a shared Double Metaphone key scoring
88.9% at 2.22% — and the script that produced them was never committed. Whatever
this module reports is now the citable number, because it can be regenerated by
anyone with the repository.

The evidence is produced by
`frontend/packages/amlfilter-publisher/src/decision/pairStudy.ts`, which scores
real alias pairs (positives) against cross-designation pairs (negatives) using
the engine's OWN `tokenSetSimilarity` / `phoneticKeys`. The metrics are assay's.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict

from amlfilter_eval.artifact import PairStudy
from amlfilter_eval.assay_seam import BinaryReport, binary_report


class RuleScore(BaseModel):
    """One decision rule measured over both populations."""

    model_config = ConfigDict(frozen=True)

    rule: str
    scores: BinaryReport


class StudyReport(BaseModel):
    """Every rule the study puts a number on."""

    model_config = ConfigDict(frozen=True)

    schema_version: int = 1
    measured_at: str
    positives: int
    negatives: int
    rules: tuple[RuleScore, ...]

    def rule(self, name: str) -> RuleScore:
        """One rule, or raise — a missing rule is a broken report, not a zero."""
        for scored in self.rules:
            if scored.rule == name:
                return scored
        raise ValueError(f"study report has no {name!r} rule")


#: The engine's ALIAS_FUZZY tier, and the rule it deliberately refuses to use.
TOKEN_SET_RULE = "token_set_ratio>=alias_fuzzy_tier"  # noqa: S105 — a rule name, not a secret
PHONETIC_RULE = "shared_double_metaphone_key"


def _score(study: PairStudy, rule: str, predictions: list[int]) -> RuleScore:
    labels = [pair.label for pair in study.pairs]
    return RuleScore(rule=rule, scores=binary_report(labels, predictions))


def build_study_report(study: PairStudy) -> StudyReport:
    """Score both rules over the emitted pairs."""
    cut = study.header.rules.aliasFuzzySetRatio
    return StudyReport(
        measured_at=study.header.measuredAt,
        positives=study.header.positives,
        negatives=study.header.negatives,
        rules=(
            _score(
                study,
                TOKEN_SET_RULE,
                [1 if p.tokenSet >= cut else 0 for p in study.pairs],
            ),
            _score(
                study,
                PHONETIC_RULE,
                [1 if p.sharedPhoneticKey else 0 for p in study.pairs],
            ),
        ),
    )
