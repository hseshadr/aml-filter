// Prebuild: derive the landing page's "real / measured" KPIs from the actual
// source files so they can never silently drift away from the truth.
//
// The public landing at "/" advertises two measured figures: how many entities
// are on the demo sanctions list, and how big the in-browser matcher model is.
// Those used to be hand-copied literals in LandingPage.tsx — a maintainer flagged
// that as a drift hazard (edit the demo list or re-export the model and the page
// lies). This script makes the files the single source of truth: it counts the
// demo bundle's records and stats the committed quantized ONNX, then emits a
// typed module the page imports.
//
//   • demo entity count = non-empty JSON lines in
//       frontend/packages/amlfilter-publisher/fixtures/demo_entities.jsonl
//   • model size MB      = statSync(public/models/.../model_quantized.onnx) bytes → MB
//
// Run by the app's `prebuild` (alongside download-model) and `pretest` hooks so
// the generated module always exists for builds and Vitest. The generated file is
// committed too (so the repo always has a valid one), but every build regenerates
// it — keeping it honest. Fail-loud: a missing source file aborts with a non-zero
// exit rather than emitting a fake number; a wrong number on a compliance landing
// is worse than a failed build.

import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The demo sanctions list whose record count the landing advertises. */
export function demoEntitiesPath() {
	const here = dirname(fileURLToPath(import.meta.url));
	return join(
		here,
		"..",
		"..",
		"packages",
		"amlfilter-publisher",
		"fixtures",
		"demo_entities.jsonl",
	);
}

/** The committed quantized ONNX matcher whose on-disk size the landing advertises. */
export function modelPath() {
	const here = dirname(fileURLToPath(import.meta.url));
	return join(
		here,
		"..",
		"public",
		"models",
		"Xenova",
		"all-MiniLM-L6-v2",
		"onnx",
		"model_quantized.onnx",
	);
}

/** Where the generated, typed stats module lands (imported by LandingPage). */
export function outputPath() {
	const here = dirname(fileURLToPath(import.meta.url));
	return join(here, "..", "src", "generated", "landing-stats.ts");
}

/** Count one entity per non-empty (non-whitespace) JSONL line. */
export function countEntities(jsonlText) {
	return jsonlText.split("\n").filter((line) => line.trim().length > 0).length;
}

/** Bytes → whole MB (decimal, 1e6), rounded to the nearest MB. */
export function bytesToMb(bytes) {
	return Math.round(bytes / 1e6);
}

/** Derive the typed DemoStats from the raw entities text and model byte count. */
export function computeStats(jsonlText, modelBytes) {
	return {
		demoEntityCount: countEntities(jsonlText),
		modelSizeMb: bytesToMb(modelBytes),
	};
}

/** Render the generated TypeScript module source for a DemoStats value. */
export function renderModule(stats) {
	return `// GENERATED by scripts/gen-demo-stats.mjs — do not edit.
// The landing page's "real / measured" KPIs, derived from the actual source
// files (the demo sanctions list + the committed quantized ONNX matcher) so the
// numbers can never silently drift. Regenerated on every build (prebuild) and
// before tests (pretest); committed so the repo always has a valid copy.

/** The measured KPIs the public landing page renders. */
export interface DemoStats {
	/** Records on the fictional demo sanctions list (frontend/packages/amlfilter-publisher/fixtures/demo_entities.jsonl). */
	readonly demoEntityCount: number;
	/** Size of the in-browser MiniLM matcher (model_quantized.onnx), in whole MB. */
	readonly modelSizeMb: number;
}

export const DEMO_STATS: DemoStats = {
	demoEntityCount: ${stats.demoEntityCount},
	modelSizeMb: ${stats.modelSizeMb},
};
`;
}

/** Read a source file's bytes, failing loudly (named) if it is absent. */
async function readBytesOrFail(path, label) {
	try {
		return await readFile(path);
	} catch (cause) {
		throw new Error(`${label}: cannot read ${path} (${cause.message})`);
	}
}

/** stat a source file's byte size, failing loudly (named) if it is absent. */
async function sizeOrFail(path, label) {
	try {
		return (await stat(path)).size;
	} catch (cause) {
		throw new Error(`${label}: cannot stat ${path} (${cause.message})`);
	}
}

/**
 * Compute the stats from the real files and write the generated module. Fails
 * loudly (rejects) if either source file is missing — never emits a fake number.
 */
export async function generateStats({ jsonlPath, modelPath: model, outPath }) {
	const jsonlText = (
		await readBytesOrFail(jsonlPath, "demo_entities.jsonl")
	).toString("utf8");
	const modelBytes = await sizeOrFail(model, "model_quantized.onnx");
	const stats = computeStats(jsonlText, modelBytes);
	await mkdir(dirname(outPath), { recursive: true });
	await writeFile(outPath, renderModule(stats));
	return stats;
}

const invokedDirectly =
	process.argv[1] !== undefined &&
	fileURLToPath(import.meta.url) === process.argv[1];

if (invokedDirectly) {
	generateStats({
		jsonlPath: demoEntitiesPath(),
		modelPath: modelPath(),
		outPath: outputPath(),
	})
		.then((stats) => {
			console.log(
				`Landing stats: ${stats.demoEntityCount} demo entities, ${stats.modelSizeMb} MB model → ${outputPath()}`,
			);
		})
		.catch((err) => {
			console.error(`\nLanding-stats generation FAILED: ${err.message}`);
			process.exit(1);
		});
}
